-- 0007 — เปลี่ยนชื่อระบบภาษาไทย (site_tagline) ให้เป็นชื่อเต็มตามที่ สอศ. ใช้
--
-- 0005 เติมค่าเริ่มต้นไว้เป็น 'ระบบติดตามความร่วมมือ' และฐานข้อมูลที่ติดตั้งไปแล้ว
-- ยังถือค่านั้นอยู่ การแก้ 0005 จะทำให้ checksum ไม่ตรง (drifted) และไม่ถูกรันซ้ำ
-- จึงต้องเป็น migration ใหม่
--
-- แก้เฉพาะแถวที่ยังเป็นค่าเดิมทั้งสองแบบ ถ้าผู้ดูแลระบบตั้งชื่อเองไว้แล้ว
-- ที่หน้า admin/settings จะไม่เขียนทับ

UPDATE `app_settings`
   SET `setting_value` = 'ระบบฐานข้อมูลความต้องการกำลังคน เพื่อการจัดการอาชีวศึกษาระบบทวิภาคี ภายใต้ความร่วมมือระหว่างสถานประกอบการและสำนักงานคณะกรรมการการอาชีวศึกษา',
       `updated_at`    = NOW()
 WHERE `setting_key`   = 'site_tagline'
   AND `setting_value` IN ('ระบบติดตามความร่วมมือ',
                           'ระบบติดตามความร่วมมือระหว่างอาชีวศึกษากับสถานประกอบการ');

-- เผื่อฐานข้อมูลที่ยังไม่มีแถวนี้ (ติดตั้งข้าม 0005 หรือถูกลบไป)
INSERT IGNORE INTO `app_settings` (`setting_key`, `setting_value`, `updated_at`) VALUES
  ('site_tagline', 'ระบบฐานข้อมูลความต้องการกำลังคน เพื่อการจัดการอาชีวศึกษาระบบทวิภาคี ภายใต้ความร่วมมือระหว่างสถานประกอบการและสำนักงานคณะกรรมการการอาชีวศึกษา', NOW());

-- @DOWN
-- ย้อนกลับเป็นชื่อเดิมที่ 0005 เติมไว้ และเฉพาะเมื่อยังเป็นชื่อใหม่ตัวนี้อยู่
UPDATE `app_settings`
   SET `setting_value` = 'ระบบติดตามความร่วมมือ',
       `updated_at`    = NOW()
 WHERE `setting_key`   = 'site_tagline'
   AND `setting_value` = 'ระบบฐานข้อมูลความต้องการกำลังคน เพื่อการจัดการอาชีวศึกษาระบบทวิภาคี ภายใต้ความร่วมมือระหว่างสถานประกอบการและสำนักงานคณะกรรมการการอาชีวศึกษา';
